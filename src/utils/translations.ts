// Build reverse translation lookup: Maps non-English phrases to their English equivalents
export const REVERSE_TO_EN_MAP = new Map<string, string>();

// Populate from translations
for (const [langKey, langObj] of Object.entries(translations)) {
  if (langKey === 'en') continue;
  for (const [key, val] of Object.entries(langObj)) {
    const enVal = translations.en[key];
    if (enVal && val) {
      REVERSE_TO_EN_MAP.set(val.trim(), enVal);
    }
  }
}

// Populate from PHRASE_DICTIONARY
for (const [langKey, phrases] of Object.entries(PHRASE_DICTIONARY)) {
  if (langKey === 'en') continue;
  for (const [enPhrase, localizedPhrase] of Object.entries(phrases)) {
    if (localizedPhrase && enPhrase) {
      REVERSE_TO_EN_MAP.set(localizedPhrase.trim(), enPhrase);
    }
  }
}

/**
 * Universal text translation engine:
 * Given any English string, key, or phrase, resolves it to the target language,
 * and if target is 'en', translates non-English text cleanly back to English.
 */
export const translateText = (text: string, lang: SupportedLanguage): string => {
  if (!text) return text;

  const trimmed = text.trim();
  if (!trimmed) return text;

  // When converting to English:
  if (lang === 'en') {
    // 1. Exact match in reverse map
    if (REVERSE_TO_EN_MAP.has(trimmed)) {
      return text.replace(trimmed, REVERSE_TO_EN_MAP.get(trimmed)!);
    }
    // 2. Direct key in translations.en
    if (translations.en[trimmed]) {
      return text.replace(trimmed, translations.en[trimmed]);
    }
    // 3. Substring replacement from reverse map
    let result = text;
    for (const [foreignPhrase, enPhrase] of REVERSE_TO_EN_MAP.entries()) {
      if (result.includes(foreignPhrase)) {
        result = result.split(foreignPhrase).join(enPhrase);
      }
    }
    return result;
  }

  // When converting to non-English language:
  // First, if text is in a foreign language (e.g. from previous language change),
  // resolve to English base first:
  let enSource = text;
  if (REVERSE_TO_EN_MAP.has(trimmed)) {
    enSource = text.replace(trimmed, REVERSE_TO_EN_MAP.get(trimmed)!);
  }
  const enTrimmed = enSource.trim();

  // 1. Direct key lookup in translations
  if (translations[lang]?.[enTrimmed]) {
    return enSource.replace(enTrimmed, translations[lang][enTrimmed]);
  }

  // 2. Direct phrase lookup in PHRASE_DICTIONARY
  if (PHRASE_DICTIONARY[lang]?.[enTrimmed]) {
    return enSource.replace(enTrimmed, PHRASE_DICTIONARY[lang][enTrimmed]);
  }

  // 3. Search key matching in en translations
  const enTranslations = translations.en;
  for (const [key, val] of Object.entries(enTranslations)) {
    if (val.toLowerCase() === enTrimmed.toLowerCase()) {
      if (translations[lang]?.[key]) {
        return enSource.replace(enTrimmed, translations[lang][key]);
      }
    }
  }

  // 4. Substring / phrase matching replacement
  let result = enSource;
  const langPhrases = PHRASE_DICTIONARY[lang] || {};
  for (const [enPhrase, localizedPhrase] of Object.entries(langPhrases)) {
    if (result.includes(enPhrase)) {
      result = result.split(enPhrase).join(localizedPhrase);
    }
  }

  return result;
};

export const getTranslation = (lang: SupportedLanguage, key: string): string => {
  if (translations[lang]?.[key]) {
    return translations[lang][key];
  }
  return translateText(key, lang);
};
